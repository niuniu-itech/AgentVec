    text = text.replace("int main(int argc,char**argv)", parser + "int main(int argc,char**argv)")
    text = re.sub(r"\(uint32_t\)atol\((argv\[\d\])\)", r"parse_size(\1)", text)
    text = re.sub(r"atoi\((argv\[\d\])\)", r"(int)parse_size(\1)", text)
    text = text.replace("std::chrono::high_resolution_clock", "std::chrono::steady_clock")
    text = re.sub(r"    n\s*=\s*\(n/\(blockDim\*\d+\)\)\*\(blockDim\*\d+\); if\(n==0\)n=blockDim\*\d+;",
                  f"    if(n % (blockDim*{sched.tile_len})) return 2;", text)
