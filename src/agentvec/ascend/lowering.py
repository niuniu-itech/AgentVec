"""Phase 3 — deterministic lowering: V-AIR (or P-AIR with a schedule) -> AscendC.

No probabilistic reasoning. Given a CHECKED AIR and a schedule (block_dim, tile_len,
buffer_num), emit a complete, self-contained AscendC kernel-launch project for the
target (Ascend310P1): the device kernel, a differential-test host harness (generates
inputs, computes a scalar oracle on the host, runs + times the kernel, reports SPR and
throughput), and the CMakeLists. Identical (AIR, sched) -> identical code.
"""
from dataclasses import dataclass
from .air import AIR, Pattern
from .guard import guard


@dataclass(frozen=True)
class Sched:
    block_dim: int = 8       # AI cores used
    tile_len: int = 1024     # elements per UB tile (MAP/REDUCE)
    buffer_num: int = 2      # double buffering
    # GEMV/GEMM tiling
    tile_m: int = 64
    tile_n: int = 64
    tile_k: int = 64

    def tag(self) -> str:
        return f"b{self.block_dim}_t{self.tile_len}_q{self.buffer_num}"


# ---------------------------------------------------------------------------
def map_kind(air: AIR) -> str:
    """Classify a MAP elem_op into {copy, scal, axpy} deterministically."""
    e = air.s_algo.elem_op
    if e.op == "load":
        return "copy"
    if e.op == "mulc":
        return "scal"
    if e.op == "add":
        return "axpy"
    raise ValueError(f"unsupported MAP elem_op {e.op}")


